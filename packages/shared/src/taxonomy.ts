/** For people living abroad. */
export const ABROAD = "Luar negeri";

const PROVINCE_OF = new Map<string, string>(REGIONS.flatMap(([prov, list]) => list.map((r) => [fold(r), prov] as const)));

/** The province a kabupaten or kota on the list belongs to. */
export const provinceOf = (region: string) => PROVINCE_OF.get(fold(region)) ?? null;

export const isRegion = (s: string) => PROVINCE_OF.has(fold(s)) || fold(s) === fold(ABROAD);

/** The place name without "Kota" or "Kab." in front, for matching it against a job's location. */
export const placeName = (region: string) =>
  region
    .split(",")[0]!
    .replace(/^\s*(kota|kab\.?|kabupaten)\s+/i, "")
    .trim();

/** Places that best match what was typed: whole-word starts first, then anywhere in the name. */
export function searchRegions(q: string, limit = 8): { region: string; province: string }[] {
  const f = fold(q);
  if (!f) return [];
  const starts: { region: string; province: string }[] = [];
  const inside: { region: string; province: string }[] = [];
  for (const [province, list] of REGIONS)
    for (const region of list) {
      const name = fold(placeName(region));
      if (name.startsWith(f) || fold(region).startsWith(f)) starts.push({ region, province });
      else if (fold(region).includes(f) || fold(province).includes(f)) inside.push({ region, province });
    }
  if (fold(ABROAD).includes(f)) starts.push({ region: ABROAD, province: "" });
  // Kota before Kab. when the names start the same, so "Bandung" offers the city first.
  starts.sort((a, b) => Number(b.region.startsWith("Kota")) - Number(a.region.startsWith("Kota")) || a.region.length - b.region.length);
  return [...starts, ...inside].slice(0, limit);
}

/** Skills on the list that match what was typed, best first, leaving out the ones already chosen. */
export function searchSkills(q: string, chosen: readonly string[] = [], limit = 8): string[] {
  const f = fold(q);
  const have = new Set(chosen.map(fold));
  const alias = SKILL_ALIASES[f];
  const out: string[] = alias && !have.has(fold(alias)) ? [alias] : [];
  if (!f) return out;
  for (const s of SKILLS) if (fold(s).startsWith(f) && !have.has(fold(s)) && !out.includes(s)) out.push(s);
  for (const s of SKILLS) if (fold(s).includes(f) && !have.has(fold(s)) && !out.includes(s)) out.push(s);
  return out.slice(0, limit);
}
