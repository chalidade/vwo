const fold = (s: string) => s.toLowerCase().replace(/\s+/g, " ").trim();
const SKILL_BY_FOLD = new Map(SKILLS.map((s) => [fold(s), s]));

/** The list's spelling of a skill, or null when it is not on the list. */
export function canonicalSkill(s: string): string | null {
  const f = fold(s);
  return SKILL_BY_FOLD.get(f) ?? SKILL_ALIASES[f] ?? null;
}

/** Most skills one profile can hold, and how many of them may be the seeker's own words. */
export const MAX_SKILLS = 15;
export const MAX_CUSTOM_SKILLS = 3;

/** A profile's skills, comma separated as stored, as a clean list: list spellings, no repeats. */
export function parseSkills(text: string | undefined): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const raw of (text ?? "").split(/[,;\n]+/)) {
    const t = raw.trim().slice(0, 40);
    if (!t) continue;
    const name = canonicalSkill(t) ?? t;
    if (seen.has(fold(name))) continue;
    seen.add(fold(name));
    out.push(name);
  }
  return out.slice(0, MAX_SKILLS);
}

export const joinSkills = (list: readonly string[]) => list.join(", ");

